'use strict';
const assert=require('node:assert/strict');
const Cult=require('../cult-system.js');
assert.equal(Cult.VERSION,1);
const fixed={id:'ritualist',name:'Unknown robed figure',occupation:'Unknown',fixed:true,branch:'temple'};
const civilian=(i)=>({id:'citizen_'+i,name:'Citizen '+i,occupation:i%2?'Merchant':'Magistrate',
  prominent:i%2===0,traits:{ambition:.9,greed:.7,fear:.3,belief:.6}});
const pool=[fixed,...Array.from({length:48},(_,i)=>civilian(i))];
const a=Cult.createWorld('world-seed-a',pool),b=Cult.createWorld('world-seed-a',pool);
const c=Cult.createWorld('world-seed-b',pool);
const summary=w=>Object.values(w.citizens).filter(x=>x.active).map(x=>x.id).sort().join(',');
assert.equal(summary(a),summary(b),'The same seed must reproduce actual cult membership');
assert.notEqual(summary(a),summary(c),'Different new worlds should vary established membership');
assert.equal(a.citizens.ritualist.fixed,true);
assert.equal(a.citizens.ritualist.active,true,'Fixed story participant remains a member');
assert.equal(Cult.board(a).length,0,'True identities must never appear on the board automatically');
assert.equal(Cult.dossier(a,'ritualist'),null,'Unmet citizens have no dossier');
let d=Cult.meet(a,'ritualist');
assert.equal(d.affiliation,'unknown','Meeting a secret member must not reveal membership');
assert.equal(Cult.board(a).length,0);
d=Cult.recordEvidence(a,'ritualist',{id:'letter1',kind:'suspicion',title:'A mysterious letter'});
assert.equal(d.affiliation,'suspected');
assert.equal(Cult.board(a).length,1);
d=Cult.recordEvidence(a,'ritualist',{id:'proof1',kind:'rank',title:'A witnessed ritual'});
assert.equal(d.affiliation,'confirmed');
assert.equal(d.rank,'member');
assert.equal(d.evidence.length,2);
Cult.recordEvidence(a,'ritualist',{id:'proof1',kind:'rank',title:'Duplicate'});
assert.equal(Cult.dossier(a,'ritualist').evidence.length,2,'Duplicate clue must not stack');
const innocent={id:'innocent',name:'Citizen without cult ties',occupation:'Physician',eligible:false};
Cult.addCitizen(a,innocent);
assert.equal(a.citizens.innocent.active,false);
Cult.meet(a,'innocent');
Cult.recordEvidence(a,'innocent',{id:'rumor',kind:'suspicion',title:'A rumor'});
assert.equal(Cult.dossier(a,'innocent').affiliation,'suspected','Innocent people may be suspected');
assert.throws(()=>Cult.recordEvidence(a,'innocent',{id:'falseproof',kind:'membership',title:'Impossible proof'}));
assert.throws(()=>Cult.recordEvidence(a,'ritualist',{id:'falseclear',kind:'innocence',title:'Impossible innocence'}));
Cult.recordEvidence(a,'innocent',{id:'alibi',kind:'innocence',title:'Verified alibi'});
assert.equal(Cult.dossier(a,'innocent').affiliation,'cleared');
assert.equal(Cult.board(a).length,1,'Exonerated people leave the cult investigation leads');
const protege={id:'protege',name:'Anonymous candidate',occupation:'Public official',eligible:false,
  branch:'district',traits:{ambition:1,greed:1,fear:1,belief:1}};
Cult.addCitizen(a,protege);
assert.equal(Cult.recruit(a,'protege',{pressure:1}),false,'Unsponsored recruitment is not allowed');
let hired=false;
for(let tries=0;tries<35&&!hired;tries++)hired=Cult.recruit(a,'protege',{by:'ritualist',pressure:1});
assert.equal(hired,true,'A motivated candidate may be recruited by an existing member');
assert.equal(Cult.dossier(a,'protege'),null,'Recruitment does not leak the secret to the player');
assert.equal(Cult.availableVacancies(a).includes('district'),true);
assert.equal(Cult.promote(a,'protege','district'),true);
assert.equal(Cult.availableVacancies(a).includes('district'),false);
Cult.meet(a,'protege');
Cult.recordEvidence(a,'protege',{id:'leader-proof',kind:'rank',title:'Observed command'});
assert.equal(Cult.dossier(a,'protege').rank,'leader');
assert.equal(Cult.depart(a,'protege'),true);
assert.equal(Cult.dossier(a,'protege').rank,'leader','Dossier must retain last known role despite hidden departure');
assert.equal(Cult.availableVacancies(a).includes('district'),true);
assert.equal(Cult.depart(a,'ritualist'),false,'Fixed member cannot silently defect');
assert.equal(Cult.kill(a,'ritualist'),true);
assert.equal(Cult.dossier(a,'ritualist').affiliation,'confirmed','A death must not rewrite player knowledge');
assert.equal(Cult.recruit(a,'protege',{by:'ritualist',pressure:1}),false,'Dead sponsors cannot recruit');
assert.equal(Cult.valid(Cult.restore(JSON.parse(JSON.stringify(a)))),true);
assert.equal(Cult.restore(JSON.parse(JSON.stringify(a))).knowledge.ritualist.evidence.length,2);
assert.throws(()=>Cult.addCitizen(a,{id:'__proto__',name:'Bad identifier'}));
console.log('PASS: seeded worlds, fixed members, hidden affiliations, proof/false leads, recruitment, promotions, persistent dossiers.');
